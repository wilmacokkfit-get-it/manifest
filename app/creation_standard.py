"""Shared comparative reasoning contract; creativity is not a safety violation."""

COMPARATIVE_STRESS_TEST = """COMPARATIVE STRESS TEST:
Before choosing a concept, privately reverse-engineer the original and donor:
buyer job, painful moment, root cause, mechanism, operating conditions and
tradeoffs. Separate the symptom from the cause. Identify which pain point the
transfer removes, which it merely moves elsewhere, and any new pain it creates.
When dated, sourced trend evidence is supplied, use the actual change in tools,
costs, access or behavior to explain why this mechanism fits now. A fashionable
name or recent launch is not proof of demand. Without current sources do not
claim live trend knowledge, and never treat earlier generated content as evidence.
Keep alternative candidates and decomposition behind the scenes. Show only the
selected mechanism, relevant pain point, concise better/worse comparison and
decisive test in the existing fields; not an analysis report or invented scores.
Do not only follow existing trends: invent plausible new habits, product
categories, rituals and business models that could create a trend. A proposed
trend does not require existing adoption. Work out who would start it, the
pain or desire that gives them a reason, why others might copy it, and the
friction that could stop it spreading. Prefer a concrete repeatable behavior
over a fashionable slogan. Preserve ambitious unfamiliar combinations.
Distinguish 'observed trend' from 'proposed trend' explicitly when discussing
trends. A new trend's spread is a hypothesis, not an adoption forecast or fact.
Describe the new behavior you propose, not an unsourced claim that an industry,
population or demand is already growing. Say 'people could start doing X because
Y' rather than 'rising X proves demand'. Unverified background assumptions must
not be introduced as 'observed reality'.
Show a concise proposed-trend rationale in why_now when available, otherwise
in description or grounding; test the first adoption assumption rather than
claiming virality, cultural leadership or guaranteed demand.
Consider several materially different cross-industry mechanisms before choosing;
select for causal fit and useful surprise, not the first familiar analogy.
For a borrowed mechanism, name what actually makes it work in the donor industry,
map that function to the host's bottleneck, and identify the dependency that must
survive the transfer (such as incentives, scale, material properties or workflow).
Explain the adaptation when that dependency differs. Borrowing an industry's
name, aesthetic or buzzword is not a mechanism. Do not claim this exploration
was market research or disclose a reasoning transcript; give the useful conclusion.
Keep the unconventional mechanism and selected merges. Safety checks constrain
hazardous execution and unsupported claims, not originality. When execution is
risky, preserve the concept and test its premise with a nonfunctional model or
qualified review; do not replace it with a conventional product just to pass.
Compare against the strongest realistic original approach for the same buyer,
task and constraints, not a straw man. Identify its specific bottleneck and WHY
it occurs, then explain how the borrowed mechanism changes that cause. If the
original is worse for this use case, explain the mechanism, not a blanket verdict.
Stress-test the advantage: name the weakest assumption and the condition where
the original still wins. Count added friction, maintenance, cost or complexity;
an improvement on one metric may sacrifice another. If equal performance is
the credible case, specify the other constraint improved. Never force superiority.
Give a falsifiable side-by-side test: same task, comparable conditions and
resources, the outcome to measure, a proposed pass/fail threshold, and the result
that would favor keeping the original or revising the merge. For safety-critical
work use a safe proxy test until qualified review permits functional testing.
Label untested causal explanations as hypotheses. Do not invent observed gains
or pretend the comparison has been run. Put the concise conclusions in existing
comparison and test fields, without extra keys, scores or a reasoning transcript.
When the schema has why_it_does, write four compact sentences labelled:
'Normal approach:' (strongest baseline and its bottleneck);
'Borrowed mechanism:' (donor function, host adaptation and required dependency);
'Hypothesis:' (causal advantage and weakest assumption);
'Original wins when:' (specific condition where its lower friction, cost or
other advantage outweighs the hybrid). A generic 'adds complexity' is not enough.
For venture schemas put the baseline comparison and original-wins condition in
grounding.exists, the transferred mechanism in description, and the fair test
in the first roadmap step. For build plans use the test step's how and done_when.
Stay within each field's length limit; sharper means more specific, not longer.
For bounded Mix fields aim for why_it_does under 800 characters and first_test
under 380 characters, leaving room below their hard limits."""
